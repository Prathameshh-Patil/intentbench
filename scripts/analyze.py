"""Error analysis of the test predictions saved by scripts/compare.py (no model is re-run).

Usage:
  python scripts/analyze.py

For each approach: the 10 most confused intent pairs with three real examples each, accuracy by
query length, and examples where the approaches disagree.
Outputs: reports/analysis.md, reports/figures/accuracy_by_length.png
"""

import json

import matplotlib.pyplot as plt
import pandas as pd

from intentbench.evaluate import FIGURES_DIR, REPORTS_DIR, SERIES, use_plot_style

APPROACHES = {
    "tfidf_logreg": "TF-IDF + LR",
    "distilbert": "DistilBERT",
    "llm": "LLM few-shot",
}
LENGTH_BINS = [0, 4, 8, 12, 100]
LENGTH_LABELS = ["1-4 words", "5-8 words", "9-12 words", "13+ words"]


def confused_pairs(df: pd.DataFrame, col: str, n: int = 10, intents_only: bool = False) -> str:
    wrong = df[df["true"] != df[col]]
    if intents_only:
        wrong = wrong[(wrong["true"] != "oos") & (wrong[col] != "oos")]
    counts = wrong.groupby(["true", col]).size().sort_values(ascending=False).head(n)
    lines = ["| True intent | Predicted | Count | Examples |", "|---|---|---|---|"]
    for (true, pred), count in counts.items():
        texts = wrong[(wrong["true"] == true) & (wrong[col] == pred)]["text"].head(3)
        examples = "<br>".join(f'"{t}"' for t in texts)
        lines.append(f"| {true} | {pred} | {count} | {examples} |")
    return "\n".join(lines)


def accuracy_by_length(df: pd.DataFrame) -> pd.DataFrame:
    words = df["text"].str.split().str.len()
    bucket = pd.cut(words, LENGTH_BINS, labels=LENGTH_LABELS)
    table = {"rows": df.groupby(bucket, observed=False).size()}
    for col, name in APPROACHES.items():
        table[name] = (df[col] == df["true"]).groupby(bucket, observed=False).mean().round(3)
    return pd.DataFrame(table)


def to_markdown(df: pd.DataFrame) -> str:
    cols = [df.index.name or "", *df.columns]
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for row in df.itertuples():
        lines.append("| " + " | ".join(map(str, row)) + " |")
    return "\n".join(lines)


def disagreements(df: pd.DataFrame) -> tuple[str, str]:
    right = pd.DataFrame({name: df[col] == df["true"] for col, name in APPROACHES.items()})
    pattern = right.apply(
        lambda r: " + ".join(n for n, ok in r.items() if ok) or "none", axis=1
    ).value_counts()
    summary = ["| Which approaches are right | Rows |", "|---|---|"]
    summary += [f"| {p} | {n} |" for p, n in pattern.items()]

    examples = [
        "| Query | True | TF-IDF + LR | DistilBERT | LLM few-shot |",
        "|---|---|---|---|---|",
    ]
    differ = df[(df["tfidf_logreg"] != df["distilbert"]) | (df["distilbert"] != df["llm"])]
    only_one_right = differ[right.loc[differ.index].sum(axis=1) == 1]
    for _, r in only_one_right.head(15).iterrows():
        cells = [r[c] if r[c] != r["true"] else f"**{r[c]}**" for c in APPROACHES]
        examples.append(f'| "{r["text"]}" | {r["true"]} | ' + " | ".join(cells) + " |")
    return "\n".join(summary), "\n".join(examples)


def plot_by_length(table: pd.DataFrame) -> None:
    use_plot_style()
    fig, ax = plt.subplots(figsize=(7, 4))
    width = 0.26
    x = range(len(table))
    for i, name in enumerate(APPROACHES.values()):
        ax.bar([p + (i - 1) * width for p in x], table[name], width, label=name, color=SERIES[i])
    ax.set_xticks(
        list(x), [f"{lab}\n(n={n})" for lab, n in zip(table.index, table["rows"], strict=True)]
    )
    ax.set_ylim(0.7, 1.0)
    ax.set_ylabel("Accuracy (incl. out-of-scope)")
    ax.set_title("Accuracy by query length, 400-row test sample", loc="left")
    ax.legend(loc="upper left", ncol=3)
    fig.tight_layout()
    fig.savefig(FIGURES_DIR / "accuracy_by_length.png", dpi=150)


def main() -> None:
    preds = pd.read_csv(REPORTS_DIR / "test_predictions.csv", index_col="row")
    results = json.loads((REPORTS_DIR / "results.json").read_text())["results"]
    sample = preds[preds["in_llm_sample"]]

    by_length = accuracy_by_length(sample)
    by_length.index.name = "Query length"
    plot_by_length(by_length)
    full_by_length = accuracy_by_length(preds.assign(llm=preds["true"])).drop(
        columns=APPROACHES["llm"]
    )
    full_by_length.index.name = "Query length"
    summary, examples = disagreements(sample)

    oos_fp = {
        name: int(((sample[col] == "oos") & (sample["true"] != "oos")).sum())
        for col, name in APPROACHES.items()
    }
    oos_fn = {
        name: int(((sample[col] != "oos") & (sample["true"] == "oos")).sum())
        for col, name in APPROACHES.items()
    }
    n_oos = int((sample["true"] == "oos").sum())

    sections = [
        "# Error analysis",
        "Generated by `python scripts/analyze.py` from the test predictions saved by "
        "`scripts/compare.py`. TF-IDF and DistilBERT use the full test set "
        f"({len(preds)} rows) where noted; anything involving the LLM uses the "
        f"{len(sample)}-row sample all three were run on. DistilBERT here is the plain model "
        "(top class); the served version with an out-of-scope threshold is in "
        "`comparison.md`. `oos` is the out-of-scope label.",
        "## Most confused intent pairs",
        "Each row is *true intent → predicted label*, with up to three real test queries.",
    ]
    for col, name in APPROACHES.items():
        scope = "400-row sample" if col == "llm" else f"full test set, {len(preds)} rows"
        data = sample if col == "llm" else preds
        sections += [f"### {name} ({scope})", confused_pairs(data, col)]
        if col != "llm":
            sections += [
                f"Intent-to-intent only ({name}), leaving out the out-of-scope rows above:",
                confused_pairs(data, col, intents_only=True),
            ]
    sections += [
        "## Out-of-scope errors on the 400-row sample",
        f"The sample has {n_oos} out-of-scope queries.",
        "| Approach | In-scope query answered `oos` (false alarm) | Out-of-scope query "
        "given an intent (missed) |\n|---|---|---|\n"
        + "\n".join(f"| {n} | {oos_fp[n]} | {oos_fn[n]} |" for n in APPROACHES.values()),
        "## Accuracy by query length",
        "![Accuracy by query length](figures/accuracy_by_length.png)",
        "400-row sample (all three approaches):",
        to_markdown(by_length),
        f"Full test set ({len(preds)} rows, local models):",
        to_markdown(full_by_length),
        "## Where the approaches disagree (400-row sample)",
        summary,
        "Examples where exactly one approach is right (the right answer in **bold**):",
        examples,
        "## Two failure patterns",
        FAILURE_PATTERNS.strip(),
        "## Recommendation",
        recommendation(results),
    ]
    (REPORTS_DIR / "analysis.md").write_text("\n\n".join(sections) + "\n")
    print((REPORTS_DIR / "analysis.md").read_text())


def recommendation(r: dict) -> str:
    t, d, dt, lm = r["tfidf_logreg"], r["distilbert"], r["distilbert_threshold"], r["llm"]
    return RECOMMENDATION.format(
        dt_f1=dt["test"]["macro_f1"],
        t_f1=t["test"]["macro_f1"],
        dt_s_acc=dt["llm_sample"]["accuracy"],
        dt_s_in=dt["llm_sample"]["in_scope_accuracy"],
        l_acc=lm["llm_sample"]["accuracy"],
        l_in=lm["llm_sample"]["in_scope_accuracy"],
        l_rec=lm["llm_sample"]["oos_recall"],
        t_ms=t["latency"]["median_ms"],
        d_ms=d["latency"]["median_ms"],
        l_ms=lm["latency"]["median_ms"],
        l_p95=lm["latency"]["p95_ms"] / 1000,
        l_cost=lm["cost_per_1000_usd"],
        t_mb=t["model_size_mb"],
        dt_rec=dt["test"]["oos_recall"],
        d_rec=d["test"]["oos_recall"],
        t_rec=t["test"]["oos_recall"],
    ).strip()


FAILURE_PATTERNS = """
**1. Out-of-scope queries that sit next to a real domain get pulled into it.** Almost every top
mistake of the two trained models is an out-of-scope query given an intent: "add mary to my phone
plan" becomes `sync_device`, "is there a better bus route" becomes `directions`, "park the car"
becomes `smart_home`. These queries share words and topic with an intent, and the training data
has very few out-of-scope examples (under 2% of train) to learn the boundary from. A classifier
trained only on "which of these 151" has no way to say "close, but none of them" except a low
confidence, which is why the threshold helps so much. The LLM, which reads the instruction "do
not force a match", misses far fewer (13 of 78 on the sample, against 36-37) but raises more
false alarms on real intents (7 against 1).

**2. Sibling intents that differ by one word of intent.** `insurance` vs `insurance_change`,
`reminder` vs `reminder_update`, `restaurant_reservation` vs `accept_reservations` /
`cancel_reservation`, `meal_suggestion` vs `restaurant_suggestion`. The topic is identical; only
the action (ask, change, cancel) differs, and often only implicitly ("help me find a new
insurance plan" means *change*). TF-IDF matches the topic words; DistilBERT and the LLM do better
but still trip when the action word is missing. More examples of the action phrasing, or merging
siblings into one intent plus a slot, would fix most of these.

**Also worth knowing.** Some "errors" are label noise in the dataset itself: five test queries
like "i would like to change the name on my checking account" are labelled `pin_change`, and
DistilBERT's `change_user_name` is arguably right. And length matters differently per approach:
TF-IDF gets worse as queries get longer (more words that dilute the telling ones), while the LLM
gets better (more context to reason with) and is weakest on 1-4 word queries like "ya".
"""


RECOMMENDATION = """
**Ship fine-tuned DistilBERT with the out-of-scope threshold as the default** (this is what the
API serves). On the 400-row sample it beats the LLM on accuracy ({dt_s_acc:.3f} vs {l_acc:.3f})
and in-scope accuracy ({dt_s_in:.3f} vs {l_in:.3f}); on the full test set its macro-F1 is
{dt_f1:.3f}. It answers in about {d_ms:.0f} ms on a laptop CPU, over 100x faster than the LLM's
{l_ms:.0f} ms median, with no per-request fee. The threshold is what makes it shippable:
out-of-scope recall goes from {d_rec:.2f} to {dt_rec:.2f}.

- **TF-IDF + logistic regression** when there is no GPU for training, the label set changes
  often (it retrains in about a minute), or the model must be tiny and explainable: macro-F1
  {t_f1:.3f} on the full test set, {t_ms:.1f} ms per request, {t_mb:.0f} MB. Its weak spot is
  out-of-scope (recall {t_rec:.2f}): add a threshold before using it in front of users.
- **An LLM** when there is little or no labelled data, or the intents change faster than you
  can collect examples. With no training it is already close (in-scope accuracy {l_in:.3f}),
  and it was the best at spotting out-of-scope queries without any tuning (recall {l_rec:.2f}).
  The price is latency (p95 {l_p95:.1f} s), a provider dependency, and ${l_cost:.2f} per 1,000
  requests, small per request but proportional to traffic.
- With about 100 labelled examples per intent, as here, fine-tuning a small transformer is worth
  the extra 12 minutes of training.

*Caveat on the sample:* macro-F1 on 400 rows rests on about two examples per intent, so a single
mistake can halve an intent's F1. Compare approaches on the sample by accuracy, and use the full
test set for macro-F1.
"""


if __name__ == "__main__":
    main()
